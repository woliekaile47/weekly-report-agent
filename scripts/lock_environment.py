"""Record tested installed dependency versions, without resolving/upgrading the environment."""

import tomllib
from collections import defaultdict, deque
from importlib import metadata
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

root = Path(__file__).resolve().parents[1]
project = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))["project"]
queue = deque(project["dependencies"] + project["optional-dependencies"]["dev"])
extras = defaultdict(set)
visited = {}
versions = {}
environment = default_environment()
while queue:
    requirement = Requirement(queue.popleft())
    if requirement.marker and not requirement.marker.evaluate({**environment, "extra": ""}):
        continue
    name = canonicalize_name(requirement.name)
    extras[name].update(requirement.extras)
    active = frozenset(extras[name] | {""})
    if visited.get(name) == active:
        continue
    visited[name] = active
    distribution = metadata.distribution(requirement.name)
    versions[name] = distribution.version
    for dep in distribution.requires or []:
        child = Requirement(dep)
        if not child.marker or any(
            child.marker.evaluate({**environment, "extra": extra}) for extra in active
        ):
            child.marker = None
            queue.append(str(child))
header = "# Tested Windows Python 3.12 runtime and dev dependency closure.\n# Generated by scripts/lock_environment.py from installed package metadata.\n# This records tested versions; it is not a cross-platform dependency solution.\n"
(root / "requirements.lock.txt").write_text(
    header + "\n".join(f"{name}=={version}" for name, version in sorted(versions.items())) + "\n",
    encoding="utf-8",
)
print(f"Recorded {len(versions)} tested dependency versions.")
